def oxml(tag, **attrs):
    el = OxmlElement(tag)
    for k, v in attrs.items():
        el.set(qn(k), v)
    return el


def set_run_font(run, name=FONT, size=13, bold=False, italic=False, color=None, rtl=True):
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    run.font.name = name
    if color is not None:
        run.font.color.rgb = color
    rPr = run._r.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = oxml("w:rFonts")
        rPr.insert(0, rFonts)
    rFonts.set(qn("w:ascii"), FONT_EN if not rtl else name)
    rFonts.set(qn("w:hAnsi"), FONT_EN if not rtl else name)
    rFonts.set(qn("w:cs"), name)
    rFonts.set(qn("w:eastAsia"), name)
    lang = rPr.find(qn("w:lang"))
    if lang is None:
        lang = oxml("w:lang")
        rPr.append(lang)
    lang.set(qn("w:val"), "fa-IR" if rtl else "en-US")
    lang.set(qn("w:bidi"), "fa-IR")
    lang.set(qn("w:eastAsia"), "en-US")
    if rtl:
        if rPr.find(qn("w:rtl")) is None:
            rPr.append(oxml("w:rtl", **{"w:val": "1"}))
        if rPr.find(qn("w:cs")) is None:
            rPr.append(oxml("w:cs"))
    else:
        rtl_el = rPr.find(qn("w:rtl"))
        if rtl_el is not None:
            rPr.remove(rtl_el)


def set_para_rtl(p, align="both", space_after=8, space_before=0, first_line=0):
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    if first_line:
        pf.first_line_indent = Cm(first_line)
    mapping = {
        "both": WD_ALIGN_PARAGRAPH.JUSTIFY,
        "right": WD_ALIGN_PARAGRAPH.RIGHT,
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "left": WD_ALIGN_PARAGRAPH.LEFT,
    }
    p.alignment = mapping.get(align, WD_ALIGN_PARAGRAPH.JUSTIFY)
    pPr = p._p.get_or_add_pPr()
    if pPr.find(qn("w:bidi")) is None:
        pPr.append(oxml("w:bidi", **{"w:val": "1"}))
    jc = pPr.find(qn("w:jc"))
    if jc is None:
        jc = oxml("w:jc")
        pPr.append(jc)
    jc.set(qn("w:val"), {"both": "both", "right": "right", "center": "center", "left": "left"}.get(align, "both"))


def add_text(p, text, **kwargs):
    run = p.add_run(text)
    set_run_font(run, **kwargs)
    return run


def body(doc, text, first=True, after=8):
    p = doc.add_paragraph()
    set_para_rtl(p, "both", space_after=after, first_line=0.7 if first else 0)
    add_text(p, text, size=13)
    return p


def para(doc, text, align="both", size=13, bold=False, color=None, after=8, before=0, first_line=0):
    p = doc.add_paragraph()
    set_para_rtl(p, align, space_after=after, space_before=before, first_line=first_line)
    add_text(p, text, size=size, bold=bold, color=color)
    return p


def heading(doc, text, level=1):
    p = doc.add_paragraph()
    p.style = doc.styles[f"Heading {level}"]
    set_para_rtl(p, "right", space_after=10, space_before=16 if level == 1 else 12)
    size = {1: 16, 2: 14, 3: 13}[level]
    color = NAVY if level == 1 else TEAL
    add_text(p, text, size=size, bold=True, color=color)
    return p


def caption(doc, text):
    p = doc.add_paragraph()
    set_para_rtl(p, "center", space_after=14, space_before=4)
    p.paragraph_format.line_spacing = 1.15
    add_text(p, text, size=11, color=NAVY)
    return p


def equation(doc, text, number=None):
    p = doc.add_paragraph()
    set_para_rtl(p, "center", space_after=10, space_before=8)
    p.paragraph_format.line_spacing = 1.15
    add_text(p, text, name=FONT_EN, size=12, rtl=False)
    if number:
        add_text(p, f"     ({number})", name=FONT, size=11, rtl=True)
    return p


def add_figure(doc, fname, cap, width=15.2):
    path = FIG / fname
    p = doc.add_paragraph()
    set_para_rtl(p, "center", space_after=2, space_before=10)
    if path.exists():
        run = p.add_run()
        run.add_picture(str(path), width=Cm(width))
    else:
        add_text(p, f"[شکل موجود نیست: {fname}]", size=11, color=RGBColor(0x99, 0x00, 0x00))
    caption(doc, cap)


def shade_cell(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    tcPr.append(oxml("w:shd", **{"w:fill": hex_color, "w:val": "clear"}))


def set_cell_border(cell):
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = oxml("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        tcBorders.append(
            oxml(f"w:{edge}", **{"w:val": "single", "w:sz": "4", "w:space": "0", "w:color": "8AA0B3"})
        )
    tcPr.append(tcBorders)


def cell_text(cell, text, bold=False, size=10, center=False, white=False):
    cell.text = ""
    p = cell.paragraphs[0]
    set_para_rtl(p, "center" if center else "right", space_after=2, space_before=2)
    p.paragraph_format.line_spacing = 1.0
    add_text(p, text, size=size, bold=bold, color=RGBColor(255, 255, 255) if white else None)
    set_cell_border(cell)


def make_table(doc, headers, rows, col_cm=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    tblPr = table._tbl.tblPr if table._tbl.tblPr is not None else oxml("w:tblPr")
    if tblPr.find(qn("w:bidiVisual")) is None:
        tblPr.append(oxml("w:bidiVisual"))
    for j, h in enumerate(headers):
        cell = table.rows[0].cells[j]
        cell_text(cell, h, bold=True, size=10, center=True, white=True)
        shade_cell(cell, HEADER_BG)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = table.rows[i + 1].cells[j]
            cell_text(cell, str(val), size=10, center=True)
            if i % 2 == 1:
                shade_cell(cell, ROW_ALT)
    if col_cm:
        for row in table.rows:
            for j, w in enumerate(col_cm):
                row.cells[j].width = Cm(w)
    p = doc.add_paragraph()
    set_para_rtl(p, "right", space_after=6, space_before=0)
    return table


def algo_box(doc, title, steps):
    para(doc, title, align="right", size=12, bold=True, color=NAVY, after=4, before=10)
    for i, step in enumerate(steps, 1):
        p = doc.add_paragraph()
        set_para_rtl(p, "both", space_after=3, first_line=0)
        p.paragraph_format.left_indent = Cm(0.4)
        p.paragraph_format.right_indent = Cm(0.3)
        add_text(p, f"{i}.  {step}", size=12)


